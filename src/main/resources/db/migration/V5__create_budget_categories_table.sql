CREATE TABLE budget_categories(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    budget_id BIGINT NOT NULL REFERENCES budgets(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    limit_amount NUMERIC(10, 2) NOT NULL,

    CONSTRAINT ck_budget_categories_limit_amount CHECK (limit_amount > 0),
    CONSTRAINT uk_budgets_categories UNIQUE (category_id, budget_id),

    FOREIGN KEY (budget_id, user_id) REFERENCES budgets(id, user_id),
    FOREIGN KEY (category_id, user_id) REFERENCES categories(id, user_id)
);